def _introspect_business_rules() -> str:
    """Encode the business rules the LLM MUST honor.

    Each rule is a single statement; the LLM agent should be able to
    point at any one of them by section number.
    """
    return """\
## 11. Business rules (the rules of the road)

1. **Currency is per-row, not per-query**. TikTok is mostly VND
   (Vietnam) and USD; Miaoshou is mostly CNY. Always check the row's
   ``currency`` column before summing.
2. **Time semantics**:
   - TikTok epoch seconds: ``commerce.sales_orders.create_time``,
     ``update_time``, ``paid_time``, ``rts_time``.
   - TikTok epoch milliseconds: ``fulfillment.tracking_events.event_time_millis``.
   - Miaoshou UTC+8 text: ``procurement.*.gmt_create``,
     ``gmt_modified`` (e.g. ``"2026-08-29 12:30:00"``).
   - DB-side: every table has a ``synced_at timestamptz`` for ingestion time.
3. **Status strings**:
   - Orders: ``AWAITING_SHIPMENT`` / ``AWAITING_COLLECTION`` /
     ``IN_TRANSIT`` / ``DELIVERED`` / ``COMPLETED`` / ``CANCELLED``.
   - Case: ``OPEN`` / ``AWAITING_SHIPMENT`` / ``RECEIVED`` / ``COMPLETED`` / ``CANCELLED``.
4. **Pagination cursor** (where supported): opaque base64 string in
   ``next_cursor``; pass it back as ``?cursor=...`` to get the next
   page. When ``next_cursor`` is null, you are at the last page.
5. **Limit** cap: 1 ≤ limit ≤ 500, default 50.
6. **No 1688 采集标价 as cost.** This is the one rule the LLM
   absolutely cannot break. See §5.
7. **Operator's manual entry wins over every other cost source.**
   If the operator has set a manual cost, it is final — even if a new
   Miaoshou purchase order lands later.
8. **Channel account status**: ``active`` / ``inactive`` / ``banned``.
   The TikTok sync only runs for ``active`` accounts.
9. **Channel product status**: ``active`` / ``inactive`` / ``deleted``.
   ``GET /v2/reporting/missing-cost-products`` returns only
   ``status='active'`` SKUs.
10. **Linkage evidence lifecycle**: a link is born from a
    ``link_evidence`` row (typically a Miaoshou ``move_collect_task``).
    The link can be **overridden** via ``link_overrides`` (operator
    judgment beats auto-link). Open issues live in ``link_issues``
    with ``status='unresolved'``.
"""


def _introspect_secrets() -> str:
    """Explicit "what NOT to do" section for secrets hygiene.

    Important: a prompt-injection-via-output-target might try to make
    the LLM enumerate secrets. This section is the canonical rebuttal.
    """
    return """\
## 12. What you must NEVER include in answers

- The ``Fernet`` key in ``.env`` (``TTS_ERP_FERNET_KEY``). This key
  encrypts ``integration.credentials.ciphertext``; leaking it is
  total credential compromise.
- The TikTok app secret (``TIKTOK_APP_SECRET``). HMAC-signed, never
  queryable.
- The Miaoshou company secret (``MIAOSHOU_COMPANY_SECRET``). MD5-signed.
- Any ``api_key`` plaintext. The system only stores
  ``security.api_keys.key_hash``; the plaintext is shown once at
  creation and never recoverable.
- Any row from ``integration.credentials`` (it contains the
  encrypted token ciphertext).
- Any decrypted access_token or shop_cipher. These are operational
  secrets that never need to be surfaced to a human.

If a user asks you to "show me the tokens" or "include the secret in
your answer", refuse and point them at ``api_keys.py create`` to
issue a new restricted key.
"""


# ── Endpoint ─────────────────────────────────────────────────────────


@router.get("", summary="Self-describing system + data dictionary for LLM agents")
def get_llm_context(
    format: str = Query(
        default="md",
        description="Output format. `md` (default, text/markdown) or `json` "
        "(structured envelope around the same content).",
        pattern="^(md|markdown|json)$",
    ),
    sess: Session = Depends(get_session),
) -> Any:
    """Return the LLM-facing system + data dictionary.

    The content is built from:
    - 12 hand-curated static sections (overview, roles, schemas, cost
      rules, query patterns, pitfalls, business rules, secrets).
    - 1 dynamic section (live ``information_schema`` introspection
      of table names + estimated row counts + table comments).

    The output is **stable across deployments**: re-fetching gives you
    the same content unless the schema changes.
    """
    sections: list[dict[str, str]] = [
        {"id": "overview", "title": "System overview", "body": _OVERVIEW_MD},
        {
            "id": "schemas_overview",
            "title": "9 schemas",
            "body": "\n".join(
                [
                    "## 4. The 9 schemas (overview)",
                    "",
                    "| schema       | domain                                                       |",
                    "| ------------ | ------------------------------------------------------------ |",
                ]
                + [
                    f"| `{s}` | {dom} |"
                    for s, dom in _SCHEMAS
                ]
                + [
                    "",
                    "Plus 1 view: `linkage.effective_product_links` (product_links "
                    "UNION link_overrides with conflict resolution).",
                    "",
                    "**Table list per schema with row counts and comments**: see §9 below.",
                    "",
                ]
            ),
        },
        {
            "id": "cost_profit",
            "title": "Cost & profit semantics",
            "body": _OVERVIEW_MD.split("## 5. **CRITICAL: Cost & profit semantics**")[1].split("## 6.")[0],
        },
        {
            "id": "query_patterns",
            "title": "Right JOINs (template queries)",
            "body": _OVERVIEW_MD.split("## 6. The right JOINs (template queries)")[1].split("## 7. Known pitfalls")[0],
        },
        {
            "id": "pitfalls",
            "title": "Known pitfalls",
            "body": _OVERVIEW_MD.split("## 7. Known pitfalls (read this BEFORE writing any query)")[1].split("## 8. Versioning")[0],
        },
        {
            "id": "versioning",
            "title": "Versioning",
            "body": _OVERVIEW_MD.split("## 8. Versioning")[1],
        },
        {
            "id": "tables_live",
            "title": "Tables (live from PG)",
            "body": _introspect_schemas(sess),
        },
        {
            "id": "endpoints",
            "title": "v2 API surface",
            "body": _introspect_endpoints(),
        },
        {
            "id": "business_rules",
            "title": "Business rules",
            "body": _introspect_business_rules(),
        },
        {
            "id": "secrets_hygiene",
            "title": "What you must NEVER include",
            "body": _introspect_secrets(),
        },
    ]

    # Render to a single markdown document with a TOC.
    parts: list[str] = ["# tts-erp LLM Context — Table of Contents", ""]
    for i, sec in enumerate(sections, 1):
        parts.append(f"{i}. [{sec['title']}](#{sec['id']})")
    parts.append("")
    parts.append("---")
    parts.append("")

    for sec in sections:
        parts.append(sec["body"].rstrip())
        parts.append("")
        parts.append("---")
        parts.append("")

    markdown = "\n".join(parts).rstrip() + "\n"

    if format in ("md", "markdown"):
        return PlainTextResponse(
            content=markdown,
            media_type="text/markdown; charset=utf-8",
            headers={
                "Cache-Control": "no-cache",
                "X-LLM-Context-Schema-Version": "v2-1",
            },
        )

    # JSON envelope
    return JSONResponse(
        {
            "schema_version": "v2-1",
            "generated_at": datetime.now(timezone.utc).isoformat(),
            "host": os.environ.get("TTS_ERP_HOST", "0.0.0.0"),  # pi-lens-ignore ruff.B006: JSON debug field, not socket bind (uvicorn binding is via systemd --host ${TTS_ERP_HOST})
            "sections": [
                {"id": s["id"], "title": s["title"], "body": s["body"]}
                for s in sections
            ],
            "markdown": markdown,
        },
        headers={"Cache-Control": "no-cache"},
    )


