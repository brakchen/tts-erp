_OVERVIEW_MD = """\
# tts-erp — Self-describing System & Data Dictionary (v2)

> Generated by `GET /v2/llm-context`. Re-fetch after any schema change.

## 1. What this system is

`tts-erp` is a **read-only analytics service** for a TikTok Shop seller
that also purchases from 妙手 (Wanshifu, the Chinese SaaS for cross-border
sourcing). It pulls data from two upstream APIs and joins them in a single
PostgreSQL database (9 schemas, 35 tables) so that the seller can answer:

- "How much profit did I make on product X last month?"
- "Which of my active TikTok SKUs have no procurement cost recorded?"
- "Which Miaoshou-sourced products are linked to which TikTok SKUs?"
- "What's the financial breakdown (commission / tax / shipping) for order O?"

## 2. Architecture in one sentence

FastAPI on :9877 (`tts_erp_v2.app`) reads from a 9-schema PostgreSQL
database. A separate `sync-worker` process (APScheduler) runs on a timer
to keep the database fresh. The two upstream APIs (TikTok Shop Open API
and Miaoshou openapi.wanshifu.com) are reached via process-internal
proxy layers (`tts_erp_v2.proxy.tts_shop`, `tts_erp_v2.proxy.miaoshou`)
that handle HMAC signing, token decryption, pagination, and rate-limit
retries. **You (the LLM) interact only with the v2 API; you do not need
to know the upstream contracts.**

## 3. Roles and auth

Three roles, hierarchical (readonly < readwrite < admin):

| role       | can call                                                 |
| ---------- | -------------------------------------------------------- |
| readonly   | all ``GET /v2/*`` endpoints                              |
| readwrite  | readonly + ``POST /v2/reporting/manual-costs``           |
| admin      | readwrite + ``POST /v2/linkage/overrides`` + other admin  |

All endpoints (except ``/healthz``, ``/endpoints``, ``/openapi.json``)
require ``Authorization: Bearer <key>`` (or ``X-API-Key: <key>``). The
key role is taken from ``security.api_keys.role``. Keys are stored as
SHA-256 hashes only; the plaintext is shown ONCE on creation via
``python3 api_keys.py create --role <role> --name <name>``.

## 4. The 9 schemas

| schema       | domain                                    | representative tables                                 |
| ------------ | ----------------------------------------- | ----------------------------------------------------- |
| integration  | 集成 / 同步运行时                          | credentials, channel_accounts, raw_records, sync_jobs |
| commerce     | TikTok 销售（订单 / 商品）                 | sales_orders, sales_order_lines, channel_products     |
| procurement  | 妙手采购 + 人工成本                        | procurement_accounts, procurement_products, manual_product_costs |
| fulfillment  | 物流                                       | shipments, shipment_lines, tracking_events            |
| after_sales  | 退货 / 取消                                | cases, case_lines                                     |
| finance      | 对账 / 打款                                | payouts, settlement_statements, settlement_transactions, settlement_components |
| linkage      | 销售 ↔ 采购关联                            | product_links, link_evidence, link_overrides, link_issues |
| reporting    | 利润 / 成本快照                            | product_cost_snapshots, product_profit_daily, shipment_tracking_summary |
| security     | API key                                    | api_keys                                              |

Plus 1 view: ``linkage.effective_product_links`` (product_links UNION
link_overrides with conflict resolution).

> **DO NOT** read ``public.*`` tables. They are legacy V1 data kept only
> for 4-week rollback safety. The v2 service code never queries them.

## 5. **CRITICAL: Cost & profit semantics**

The cost used to compute profit is the **first available** in this order:

1. **MANUAL_ENTRY** — operator-entered cost in
   ``procurement.manual_product_costs`` (highest priority).
2. **Miaoshou purchase order** line price (in ``procurement.purchase_order_lines``).
3. *(1688 采集标价 is **explicitly excluded** — it is a stale initial quote
   that does not reflect the actual negotiated procurement price. Using
   it would systematically over-state costs and under-state profit.)*

If a TikTok active SPU has **no cost from sources 1 or 2**, it shows up in
``GET /v2/reporting/missing-cost-products`` — operators fill those via
``POST /v2/reporting/manual-costs`` (or the HTML form at
``GET /v2/pages/manual-costs``).

**Implication for queries**: never join against
``miaoshou_move_collect_tasks.platform_item_id`` as a cost proxy. Always
look up cost via the priority chain above. The
``reporting.product_profit_daily`` and ``reporting.product_cost_snapshots``
tables already encode this — **prefer reading those over recomputing**.

## 6. The right JOINs (template queries)

- **Sales per SKU per day** → ``commerce.sales_order_lines`` joined to
  ``commerce.sales_orders`` and ``commerce.channel_products``.
- **Profit per SKU per day** → ``reporting.product_profit_daily``
  (pre-aggregated, currency-normalized within the row's ``currency``).
- **Miaoshou product ↔ TikTok SPU** → ``linkage.effective_product_links``
  (the view; use this, not ``linkage.product_links`` directly, because
  overrides change the answer).
- **Active SPU without cost** → ``GET /v2/reporting/missing-cost-products``
  (or the ``commerce.channel_products`` rows that have no
  ``procurement.manual_product_costs`` row with ``valid_to IS NULL``
  AND no effective link).
- **Time semantics**: TikTok ``update_time`` / ``create_time`` are
  **epoch seconds**; ``tracking_events.event_time_millis`` are
  **epoch milliseconds**; Miaoshou ``gmt_create`` / ``gmt_modified`` are
  **UTC+8 text strings** (``"2026-08-29 12:30:00"``). Don't mix them.

## 7. Known pitfalls (read this BEFORE writing any query)

- DO NOT compute profit using 1688 采集标价. See §5.
- DO NOT read ``public.*`` tables. They are V1 rollback safety only.
- DO NOT use ``linkage.product_links`` directly — use
  ``linkage.effective_product_links`` (overrides change the answer).
- DO NOT assume a single ``currency`` per query. TikTok has VND/USD
  orders; Miaoshou is mostly CNY. Use the row's ``currency`` column.
- DO NOT join ``sales_order_lines`` to ``channel_products`` via
  ``product_id`` alone — use ``channel_product_id`` (FK) for the
  authoritative link. The raw product id strings are also stored in
  ``external_product_id_snapshot`` for audit.
- DO NOT call ``POST /orders/*`` write endpoints — they are 404 in v2.
  The architecture is read-only analytics; order writes were removed.
- DO NOT recompute cost from raw Miaoshou move-collect tasks — that
  table is the *evidence* of a link, not the cost.

## 8. Versioning

- v2 is live on ``master`` since commit ``1d8ed0d`` (2026-08-30).
- V1 endpoints (``/orders/*``, ``/finance/*``, ``/db/*``, ``/sync/*``,
  ``/miaoshou/*``) return 404 from the v2 app.
- ``public.*`` (V1 data) is preserved for 4 weeks post-cutover, then
  archived (see ``prod-switch/observe-archive.sh``).

---
"""


