"""v2/llm-context — self-describing system + data dictionary for LLM agents.

Auth: readonly (any authenticated key). GET only.

Purpose
-------
LLM agents (Claude, ChatGPT, in-house copilots) need a single canonical
document that tells them:

1. **What this system is** and what business questions it can answer.
2. **How data is shaped** — every schema, every table, every important
   column, with type, nullability, and FK relationships.
3. **How to call the v2 API** — which endpoints exist, what role they
   need, what query params they accept.
4. **The cost & profit semantics** — which is the highest-priority cost
   source, which MUST NOT be used, and why.
5. **The common query patterns** — the right JOINs to use for sales,
   profit, coverage, missing-cost analysis.

This endpoint is a **prompt-engineering artifact** for the LLM. The
content is generated dynamically from the live PG schema (so a table
rename or column add is reflected automatically) plus a curated set of
static guidance sections that encode the team's business rules.

Endpoint contract
-----------------
- ``GET /v2/llm-context``              → text/markdown (default for LLMs)
- ``GET /v2/llm-context?format=md``   → same as above
- ``GET /v2/llm-context?format=json`` → ``{schema_version, generated_at,
                                       key_role, markdown, sections: [...]}``

What this endpoint does NOT include (secrets, noise)
---------------------------------------------------
- No app_secret, no Fernet key, no Fernet-encrypted ciphertext.
- No api_key plaintext, no api_key_hash.
- No row data (only schema + business rules). Run the v2 endpoints for
  actual data.
- No ``public.*`` legacy tables (those will be archived after the
  4-week observation window).
"""
